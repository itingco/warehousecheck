USE DB_AppHub;
GO

SELECT
    TABLE_NAME,
    ORDINAL_POSITION,
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME IN ('ItemBarcode', 'ItemRatio')
ORDER BY TABLE_NAME, ORDINAL_POSITION;
GO

SELECT TOP 5 *
FROM ItemBarcode;
GO

SELECT TOP 20 *
FROM ItemRatio;
GO

SELECT TOP 20 *
FROM ItemBarcode
LEFT JOIN ItemRatio
    ON ItemRatio.ItemCode = ItemBarcode.ItemCode;
GO
